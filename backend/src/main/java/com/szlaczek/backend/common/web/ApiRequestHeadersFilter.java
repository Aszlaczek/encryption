package com.szlaczek.backend.common.web;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.ServletInputStream;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletRequestWrapper;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.util.Locale;
import java.util.UUID;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.InvalidMediaTypeException;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

/**
 * Applies API-wide transport rules before Spring Security runs: a trusted request id, a strict body size limit and
 * cache headers. The request id is always generated by the server; a client-supplied value is ignored.
 */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class ApiRequestHeadersFilter extends OncePerRequestFilter {

    public static final String REQUEST_ID_HEADER = "X-Request-Id";
    public static final String TRACE_ID_ATTRIBUTE = ApiRequestHeadersFilter.class.getName() + ".traceId";

    static final int MAX_REQUEST_BODY_BYTES = 65_536;

    private final ApiProblemWriter problemWriter;

    public ApiRequestHeadersFilter(ApiProblemWriter problemWriter) {
        this.problemWriter = problemWriter;
    }

    @Override
    protected void doFilterInternal(
            HttpServletRequest request, HttpServletResponse response, FilterChain filterChain)
            throws ServletException, IOException {
        String traceId = UUID.randomUUID().toString().replace("-", "");
        request.setAttribute(TRACE_ID_ATTRIBUTE, traceId);
        response.setHeader(REQUEST_ID_HEADER, traceId);

        if (isApiRequest(request)) {
            response.setHeader(HttpHeaders.CACHE_CONTROL, "no-store");
            response.setHeader("X-Content-Type-Options", "nosniff");
        }

        if (isApiRequest(request) && request.getContentLengthLong() > MAX_REQUEST_BODY_BYTES) {
            problemWriter.write(
                    request,
                    response,
                    HttpStatus.CONTENT_TOO_LARGE,
                    "PAYLOAD_TOO_LARGE",
                    "Żądanie przekracza 65 536 bajtów.");
            return;
        }

        if (requiresJsonContentType(request) && !isJsonUtf8(request)) {
            problemWriter.write(
                    request,
                    response,
                    HttpStatus.UNSUPPORTED_MEDIA_TYPE,
                    "UNSUPPORTED_MEDIA_TYPE",
                    "Wymagany jest Content-Type: application/json w UTF-8.");
            return;
        }

        try {
            if (isApiRequest(request)) {
                filterChain.doFilter(new SizeLimitedRequest(request), response);
            } else {
                filterChain.doFilter(request, response);
            }
        } catch (PayloadTooLargeException exception) {
            problemWriter.write(
                    request,
                    response,
                    HttpStatus.CONTENT_TOO_LARGE,
                    "PAYLOAD_TOO_LARGE",
                    "Żądanie przekracza 65 536 bajtów.");
        }
    }

    private boolean isApiRequest(HttpServletRequest request) {
        String uri = request.getRequestURI();
        return uri != null && (uri.equals("/api") || uri.startsWith("/api/"));
    }

    private boolean requiresJsonContentType(HttpServletRequest request) {
        if (!isApiRequest(request)) {
            return false;
        }

        String method = request.getMethod();
        if (!"POST".equals(method) && !"PUT".equals(method) && !"PATCH".equals(method)) {
            return false;
        }

        // Logout deliberately has no body and therefore no content type.
        String uri = request.getRequestURI();
        return !"/api/auth/logout".equals(uri) && !uri.matches("^/api/messages/[^/]+/decrypt$");
    }

    private boolean isJsonUtf8(HttpServletRequest request) {
        String contentType = request.getContentType();
        if (contentType == null || contentType.isBlank()) {
            return false;
        }

        try {
            MediaType mediaType = MediaType.parseMediaType(contentType);
            if (!MediaType.APPLICATION_JSON.isCompatibleWith(mediaType)) {
                return false;
            }

            var charset = mediaType.getCharset();
            return charset == null || "UTF-8".equals(charset.name().toUpperCase(Locale.ROOT));
        } catch (InvalidMediaTypeException exception) {
            return false;
        }
    }

    private static final class SizeLimitedRequest extends HttpServletRequestWrapper {

        private SizeLimitedRequest(HttpServletRequest request) {
            super(request);
        }

        @Override
        public ServletInputStream getInputStream() throws IOException {
            return new SizeLimitedInputStream(super.getInputStream());
        }
    }

    private static final class SizeLimitedInputStream extends ServletInputStream {

        private final ServletInputStream delegate;
        private long bytesRead;

        private SizeLimitedInputStream(ServletInputStream delegate) {
            this.delegate = delegate;
        }

        @Override
        public int read() throws IOException {
            int value = delegate.read();
            if (value != -1) {
                count(1);
            }
            return value;
        }

        @Override
        public int read(byte[] buffer, int offset, int length) throws IOException {
            int read = delegate.read(buffer, offset, length);
            if (read > 0) {
                count(read);
            }
            return read;
        }

        @Override
        public int read(byte[] buffer) throws IOException {
            int read = delegate.read(buffer);
            if (read > 0) {
                count(read);
            }
            return read;
        }

        @Override
        public long skip(long length) throws IOException {
            long skipped = delegate.skip(length);
            if (skipped > 0) {
                count(skipped);
            }
            return skipped;
        }

        @Override
        public int available() throws IOException {
            return delegate.available();
        }

        @Override
        public void close() throws IOException {
            delegate.close();
        }

        @Override
        public boolean isFinished() {
            return delegate.isFinished();
        }

        @Override
        public boolean isReady() {
            return delegate.isReady();
        }

        @Override
        public void setReadListener(jakarta.servlet.ReadListener readListener) {
            delegate.setReadListener(readListener);
        }

        private void count(long read) throws PayloadTooLargeException {
            bytesRead += read;
            if (bytesRead > MAX_REQUEST_BODY_BYTES) {
                throw new PayloadTooLargeException("Request body exceeds " + MAX_REQUEST_BODY_BYTES + " bytes");
            }
        }
    }
}
